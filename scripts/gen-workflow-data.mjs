// Extracts the topology from the user-supplied workflow demo HTML into a typed
// module. Topology/timings are copied verbatim; only node/screen geometry
// (sizes, ports, bezier control points) is derived with the demo's own rules.
//
//   node scripts/gen-workflow-data.mjs
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'screenshot/工作流视频展示版.html';
const OUT = 'src/promo/shots/workflow/workflowData.ts';

const html = fs.readFileSync(SRC, 'utf8');
const start = html.indexOf('const data=') + 'const data='.length;
let end = html.indexOf(';\r\nconst $=', start);
if (end < 0) end = html.indexOf(';\nconst $=', start);
const data = JSON.parse(html.slice(start, end));

const styleFor = (type) => {
  if (type.endsWith('.agent')) return ['✧', '#8b73c6', 'agent', 'AI Agent'];
  if (/lmChat/.test(type)) return ['✧', '#8e73c8', 'support', 'Chat Model'];
  if (/memory/.test(type)) return ['▤', '#799ba3', 'support', 'Memory'];
  const t = type.split('.').pop();
  const table = {
    webhook: ['↪', '#c36dba', 'webhook', 'Webhook'],
    code: ['{ }', '#e6a16d', 'code', 'Code'],
    if: ['⑂', '#6aa88b', 'if', 'IF'],
    switch: ['⑂', '#699bc5', 'switch', 'Switch'],
    postgres: ['▥', '#698fb0', 'postgres', 'Postgres'],
    redis: ['▰', '#bf5a57', 'redis', 'Redis'],
    httpRequest: ['◎', '#8c7bc8', 'http', 'HTTP Request'],
    set: ['☷', '#779fbd', 'set', 'Edit Fields'],
    wait: ['⌛', '#b38499', 'wait', 'Wait'],
    merge: ['⋈', '#799c89', 'merge', 'Merge'],
    googleSheets: ['▦', '#6aa77d', 'sheets', 'Google Sheets'],
  };
  return [...(table[t] ?? ['◇', '#969dab', 'other', t])];
};

const minX = Math.min(...data.nodes.map((n) => n.position[0])) - 130;
const minY = Math.min(...data.nodes.map((n) => n.position[1])) - 160;

const seen = new Set();
const nodes = data.nodes.map((n) => {
  if (seen.has(n.name)) throw new Error(`duplicate node name: ${n.name}`);
  seen.add(n.name);
  const [glyph, color, kind, sub] = styleFor(n.type);
  const support = /lmChat|memory/.test(n.type);
  const agent = n.type.endsWith('.agent');
  const w = agent ? 208 : support ? 76 : 96;
  const h = support ? 76 : 96;
  return {
    name: n.name,
    kind,
    sub,
    glyph,
    color,
    x: n.position[0] - minX,
    y: n.position[1] - minY,
    w,
    h,
    disabled: Boolean(n.disabled),
  };
});
const nodeMap = new Map(nodes.map((n) => [n.name, n]));

const outputsOf = (source) =>
  Math.max(
    nodeMap.get(source).kind === 'if' ? 2 : 1,
    ...data.edges
      .filter((e) => e.source === source && e.kind === 'main')
      .map((e) => e.output + 1),
  );

const edges = data.edges.map((e) => {
  const a = nodeMap.get(e.source);
  const b = nodeMap.get(e.target);
  if (!a || !b) throw new Error(`missing node for edge ${e.source}->${e.target}`);
  let p;
  if (e.kind !== 'main') {
    const sx = a.x + a.w / 2;
    const sy = a.y;
    const tx = b.x + b.w / 2 + (e.kind.includes('memory') ? 35 : -25);
    const ty = b.y + b.h;
    p = [sx, sy, sx, sy - 80, tx, ty + 80, tx, ty];
  } else {
    const count = outputsOf(e.source);
    const sx = a.x + a.w;
    const sy = a.y + (a.h * (e.output + 1)) / (count + 1);
    const tx = b.x;
    const ty = b.y + b.h / 2;
    const bend = Math.max(65, Math.abs(tx - sx) * 0.46);
    p = [sx, sy, sx + bend, sy, tx - bend, ty, tx, ty];
  }
  return { s: e.source, t: e.target, kind: e.kind, out: e.output, p };
});

const demoEdges = data.demo.edges.map((d) => ({
  s: d.edge.source,
  t: d.edge.target,
  kind: d.edge.kind,
  out: d.edge.output,
  start: Math.round(d.start * 100) / 100,
  end: Math.round(d.end * 100) / 100,
}));

const world = {
  w: Math.round(Math.max(...nodes.map((n) => n.x + n.w)) + 170),
  h: Math.round(Math.max(...nodes.map((n) => n.y + n.h)) + 170),
};

const r1 = (v) => Math.round(v * 100) / 100;
const lines = [];
lines.push("// Generated by scripts/gen-workflow-data.mjs from screenshot/工作流视频展示版.html.");
lines.push('// Topology, node positions and demo timings are copied from the source; do not hand-edit.');
lines.push('export type WorkflowNode = {');
lines.push('  name: string; kind: string; sub: string; glyph: string; color: string;');
lines.push('  x: number; y: number; w: number; h: number; disabled: boolean;');
lines.push('};');
lines.push('export type WorkflowEdge = {');
lines.push('  s: string; t: string; kind: string; out: number;');
lines.push('  p: [number, number, number, number, number, number, number, number];');
lines.push('};');
lines.push('export type DemoEdge = { s: string; t: string; kind: string; out: number; start: number; end: number };');
lines.push(`export const WORLD = { w: ${world.w}, h: ${world.h} } as const;`);
lines.push(`export const DEMO = { duration: ${data.demo.duration}, split: ${JSON.stringify(data.demo.split)}, merge: ${JSON.stringify(data.demo.merge)} } as const;`);
lines.push('export const ROUTE: string[] = [');
lines.push(data.route.map((r) => `  ${JSON.stringify(r.name)},`).join('\n'));
lines.push('];');
lines.push('export const NODES: WorkflowNode[] = [');
lines.push(
  nodes
    .map(
      (n) =>
        `  { name: ${JSON.stringify(n.name)}, kind: ${JSON.stringify(n.kind)}, sub: ${JSON.stringify(
          n.sub,
        )}, glyph: ${JSON.stringify(n.glyph)}, color: ${JSON.stringify(n.color)}, x: ${r1(n.x)}, y: ${r1(
          n.y,
        )}, w: ${n.w}, h: ${n.h}, disabled: ${n.disabled} },`,
    )
    .join('\n'),
);
lines.push('];');
lines.push('export const EDGES: WorkflowEdge[] = [');
lines.push(
  edges
    .map(
      (e) =>
        `  { s: ${JSON.stringify(e.s)}, t: ${JSON.stringify(e.t)}, kind: ${JSON.stringify(
          e.kind,
        )}, out: ${e.out}, p: [${e.p.map(r1).join(', ')}] },`,
    )
    .join('\n'),
);
lines.push('];');
lines.push('export const DEMO_EDGES: DemoEdge[] = [');
lines.push(
  demoEdges
    .map(
      (e) =>
        `  { s: ${JSON.stringify(e.s)}, t: ${JSON.stringify(e.t)}, kind: ${JSON.stringify(e.kind)}, out: ${
          e.out
        }, start: ${e.start}, end: ${e.end} },`,
    )
    .join('\n'),
);
lines.push('];');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
console.log(
  `wrote ${OUT}: ${nodes.length} nodes, ${edges.length} edges, route ${data.route.length}, demo ${demoEdges.length}`,
);
